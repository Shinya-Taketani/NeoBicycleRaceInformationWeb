class Service
{
    public function __construct(private readonly Sources $sources, private readonly OuterSource $outer, private readonly Bundle $bundle,
        private readonly Code $code, private readonly Trend $trend) {}

    public function execute(string $root, string $id, string $score, string $outer, string $meeting): array
    {
        $sources = $this->sources->open($score, $outer, $meeting);
        $this->bundle->prepare($root, $id, $sources['files']);

        return $this->bundle->writer->locked($root, $id, function () use ($root, $id, $sources): array {
            $stage = Files::directory($root.'/.staging/'.$id.'-'.bin2hex(random_bytes(6)));
            $result = $this->generate($stage, $sources);
            $this->bundle->publish($stage, $root.'/evaluations/'.$id, Contract::plan(), $result['expected']);

            return ['status' => $result['selection']['status'], 'selected' => $result['selection']['selected'], 'bundle' => $root.'/evaluations/'.$id, 'database' => 'NONE', 'memory_peak' => memory_get_peak_usage(true)];
        });
    }

    public function reproduce(string $root, string $id): array
    {
        $path = $root.'/evaluations/'.$id;
        $manifest = $this->bundle->verify($path, Contract::plan());
        Files::same(Files::json($path.'/code.json'), $this->code->capture(), 'reproduce code');
        $sources = Files::json($path.'/sources.json');
        OuterSource::verify($sources['files']);

        return $this->bundle->writer->locked($root, $id, function () use ($root, $id, $path, $sources, $manifest): array {
            $stage = Files::directory($root.'/.staging/'.$id.'-reproduce-'.bin2hex(random_bytes(6)));
            $result = $this->generate($stage, $sources);
            Files::same($manifest['files'], $result['expected'], 'all generated bytes');
            foreach ($result['expected'] as $name => $seal) {
                Files::verify($path.'/'.$name, $seal);
            }
            $report = ['status' => 'BYTE_EXACT', 'files' => count($result['expected']), 'database' => 'NONE', 'stage' => $stage, 'memory_peak' => memory_get_peak_usage(true)];
            $this->bundle->writer->event($root, $id, $report);

            return $report;
        });
    }

    public function generate(string $stage, array $sources, ?callable $afterSeal = null): array
    {
        $writer = $this->bundle->writer;
        $code = $this->code->capture();
        OuterSource::verify($sources['files']);
        $access = new TemporalAccess;
        $access->record('SCORE_SOURCE_VERIFIED');
        $access->record('OUTCOME_FREE_SOURCE_PROJECTED');
        $w = new Workspace($stage.'/spool.sqlite');
        $w->targets($this->outer->targets($sources['outer']));
        $w->observations(JsonlArtifact::read($sources['score'].'/score-observations.jsonl'));
        $w->representatives($this->trend);
        $w->metadata($sources['meeting']);
        $s = new Statistics($w->db);
        $audit = (new Audit)->run($w, $s);
        $expected = [];
        $representatives = (function () use ($w): \Generator {
            foreach ($w->db->query('SELECT body FROM meetings ORDER BY player_id,order_date,meeting_id') as $row) {
                yield json_decode($row['body'], true, flags: JSON_THROW_ON_ERROR);
            }
        })();
        $expected += $writer->writeJsonl($stage, 'meeting-representatives.jsonl', $representatives);
        foreach (['contract.json' => Contract::plan(), 'sources.json' => $sources, 'code.json' => $code,
            'score-source-verification.json' => ['manifest' => Files::identity($sources['score'].'/manifest.json'), 'status' => 'VERIFIED'],
            'candidate-grid.json' => Contract::grid(), 'granularity-audit.json' => $audit] as $name => $data) {
            $expected += $writer->writeJson($stage, $name, $data);
        }
        $access->record('TREND_INPUT_STARTED');
        $expected += $writer->writeJsonl($stage, 'trend-input.jsonl', $w->inputs($sources['outer'], $this->trend));
        $bins = $s->bins();
        $expected += $writer->writeJson($stage, 'ability-bins.json', $bins);
        $expected += $writer->writeJson($stage, 'day-start-exclusions.json', [
            'source_observations_missing_start' => (int) $w->db->query('SELECT count(*) FROM observations WHERE start IS NULL')->fetchColumn(),
            'source_meetings_missing_start' => (int) $w->db->query('SELECT count(DISTINCT meeting_id) FROM observations WHERE start IS NULL')->fetchColumn(),
            'unit' => 'EXCLUDED_TARGET_PRIOR_MEETING_PAIRS; UNKNOWN_START_CANNOT_BE_ASSIGNED_TO_A_WINDOW',
            'candidates' => $w->db->query('SELECT * FROM day_exclusions ORDER BY year,candidate')->fetchAll()]);
        $sealed = array_intersect_key($expected, array_flip(['contract.json', 'sources.json', 'code.json', 'candidate-grid.json', 'score-source-verification.json', 'trend-input.jsonl', 'trend-input.jsonl.manifest.json', 'ability-bins.json']));
        $expected += $writer->writeJson($stage, 'trend-input-seal.json', $sealed);
        $access->seal($stage, $sealed);
        if ($afterSeal !== null) {
            $afterSeal($stage);
        }
        $expected += $writer->writeJson($stage, 'outcome-isolation-audit.json', [
            'preseal_artifacts' => array_keys($sealed), 'outcome_hashes_present_preseal' => false,
            'meeting_bundle_whole_manifest_identity_present_preseal' => false, 'outer_whole_export_manifest_identity_present_preseal' => false,
            'outer_outcome_free_projection_sha256' => $sources['outer']['outcome_free_projection_sha256'],
            'meeting_metadata_projection_sha256' => $sources['meeting_metadata_projection_sha256']]);
        $w->outcomes($sources['outer'], $access, $this->outer);
        $expected += $writer->writeJson($stage, 'outcome-sources.json', $access->sources());
        $years = $first = $conditional = [];
        foreach ([2024, 2025] as $year) {
            foreach (Contract::grid() as $c) {
                $m = $s->metrics($c['id'], $year);
                $m['first_observation'] = $s->metrics($c['id'], $year, 'e.first_obs=1', conditional: false);
                $years[$year][$c['id']] = $m;
                $first[$year][$c['id']] = $m['first_observation'];
                $conditional[$year][$c['id']] = ['score' => $m['score_conditional'], 'c1' => $m['c1_conditional']];
            }
            $expected += $writer->writeJson($stage, 'candidate-results-'.$year.'.json', $years[$year]);
            $expected += $this->csv($stage, 'candidate-results-'.$year.'.csv', $years[$year]);
        }
        $selection = (new Selection)->select($years);
        $access->record('SELECTION_COMPUTED');
        $coverage = $s->query('SELECT e.year,s.candidate,s.state,count(*) AS n FROM signals s JOIN entries e ON e.entry_id=s.entry_id GROUP BY e.year,s.candidate,s.state ORDER BY e.year,s.candidate,s.state')->fetchAll();
        $summary = ['status' => $selection['status'], 'selected' => $selection['selected'], 'years' => [], 'interpretation' => 'DEVELOPMENT_SELECTION_NOT_UNSEEN_VALIDATION_OR_MODEL_IMPROVEMENT'];
        if ($selection['selected'] !== null) {
            foreach ([2024, 2025] as $year) {
                $summary['years'][$year] = $years[$year][$selection['selected']['id']];
            }
        }
        $outputs = ['coverage.json' => $coverage, 'conditional-results.json' => $conditional, 'first-observation-robustness.json' => $first,
            'granularity-selection.json' => $selection, 'family-ranking.json' => $selection['family_ranking'], 'selected-summary.json' => $summary,
            'temporal-access-audit.json' => $access->artifact()];
        $outputs += (new Diagnostics)->run($s, $selection, $years, $audit);
        $outputs['old-race-growth-comparison.json'] = $this->old($w, $s, $access, $years, $selection);
        $outputs['review-fix-comparison.json'] = $this->comparison($sources, $years, $selection, $outputs, $expected, $access);
        foreach ($outputs as $name => $data) {
            $expected += $writer->writeJson($stage, $name, $data);
        }
        $expected += $this->csv($stage, 'selected-summary.csv', $summary['years']);
        OuterSource::verify($sources['files']);
        foreach ($access->sources() as $outcome) {
            OuterSource::verify($outcome['files']);
            OuterSource::verify($outcome['registry']);
        }
        Files::same($sources, $this->sources->open($sources['score'], $sources['outer']['root'], $sources['meeting']), 'source projections END');
        Files::same($code, $this->code->capture(), 'analysis code END');
        $expected += $writer->writeJson($stage, 'source-end.json', ['status' => 'UNCHANGED', 'files' => $sources['files'], 'outcomes' => $access->sources(), 'code' => $code]);
        unset($s, $w);
        unlink($stage.'/spool.sqlite');

        return compact('expected', 'selection');
    }

