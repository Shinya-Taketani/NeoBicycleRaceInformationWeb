    protected function comparison(array $sources, array $years, array $selection, array $outputs, array $expected, TemporalAccess $access): array
    {
        return (new ReviewComparison)->report($sources, $years, $selection, $outputs, $expected, $access);
    }

    private function csv(string $stage, string $name, array $rows): array
    {
        $h = fopen($stage.'/'.$name, 'xb');
        $hash = hash_init('sha256');
        $bytes = 0;
        $write = function (array $row) use ($h, $hash, &$bytes): void {
            $line = implode(',', $row)."\n";
            if (fwrite($h, $line) !== strlen($line)) {
                throw new RuntimeException('CSV write failed.');
            }
            hash_update($hash, $line);
            $bytes += strlen($line);
        };
        try {
            $write(['candidate_or_year', 'valid_entries', 'normal_entries', 'coverage', 'zero_rate', 'overall_rho', 'score_conditional_rho', 'c1_conditional_rho', 'first_rho', 'fp_pos_minus_neg']);
            foreach ($rows as $id => $m) {
                $values = [$m['valid_entries'], $m['normal_entries'], $m['coverage'], $m['zero_rate'], $m['overall']['rho'],
                    $m['score_conditional']['rho'], $m['c1_conditional']['rho'], $m['first_observation']['overall']['rho'], $m['fp_pos_minus_neg']];
                $write([(string) $id, ...array_map(fn ($v) => $v === null ? '' : sprintf('%.17g', $v), $values)]);
            }
            fflush($h);
            fsync($h);
        } finally {
            fclose($h);
        }
        $seal = ['bytes' => $bytes, 'sha256' => hash_final($hash)];
        Files::verify($stage.'/'.$name, $seal);

        return [$name => $seal];
    }
